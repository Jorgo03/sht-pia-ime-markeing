#!/usr/bin/env node
// Builds assets/illustrations/albania-map.svg + albania-map.json from Natural Earth
// (public domain). Run once; the outputs are committed, so renders never fetch.
//
//   node scripts/build-map.mjs [path/to/ne_10m_admin_0_countries.geojson]
//
// Without an argument it downloads the file from the Natural Earth GitHub mirror.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';

// Frame: lon 18.2–21.5, lat 39.5–42.8 (Albania with a margin of its neighbours).
const BOX = { lon0: 18.2, lon1: 21.5, lat0: 39.5, lat1: 42.8 };
const W = 1000;
const K = Math.cos(((BOX.lat0 + BOX.lat1) / 2) * Math.PI / 180);
const H = Math.round(W * (BOX.lat1 - BOX.lat0) / ((BOX.lon1 - BOX.lon0) * K));
const px = ([lon, lat]) => [
  +((lon - BOX.lon0) / (BOX.lon1 - BOX.lon0) * W).toFixed(1),
  +((BOX.lat1 - lat) / (BOX.lat1 - BOX.lat0) * H).toFixed(1),
];

// Real coordinates (WGS84) of places the app's demo listings and ads use.
export const CITIES = {
  tirane: { name: 'Tiranë', lon: 19.8187, lat: 41.3275 },
  durres: { name: 'Durrës', lon: 19.4414, lat: 41.3231 },
  vlore: { name: 'Vlorë', lon: 19.4914, lat: 40.4661 },
  shkoder: { name: 'Shkodër', lon: 19.5126, lat: 42.0683 },
  sarande: { name: 'Sarandë', lon: 20.0053, lat: 39.8756 },
  gjirokaster: { name: 'Gjirokastër', lon: 20.1389, lat: 40.0758 },
  dhermi: { name: 'Dhërmi', lon: 19.6403, lat: 40.1525 },
  korce: { name: 'Korçë', lon: 20.7808, lat: 40.6186 },
  elbasan: { name: 'Elbasan', lon: 20.0822, lat: 41.1125 },
  berat: { name: 'Berat', lon: 19.9522, lat: 40.7058 },
};

const want = { ALB: 'albania', MNE: 'montenegro', KOS: 'kosovo', MKD: 'north-macedonia', GRC: 'greece', SRB: 'serbia', ITA: 'italy' };

async function load(file) {
  if (file) return JSON.parse(fs.readFileSync(file, 'utf8'));
  const res = await fetch(SRC);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  return res.json();
}

function ringPath(ring) {
  // Drop points that land on the same pixel, then clip loosely to the frame.
  const pts = [];
  for (const c of ring) {
    const p = px(c);
    const last = pts[pts.length - 1];
    if (!last || Math.abs(last[0] - p[0]) > 0.6 || Math.abs(last[1] - p[1]) > 0.6) pts.push(p);
  }
  const inside = pts.some(([x, y]) => x > -200 && x < W + 200 && y > -200 && y < H + 200);
  if (!inside || pts.length < 3) return '';
  return 'M' + pts.map((p) => p.join(',')).join('L') + 'Z';
}

const geo = await load(process.argv[2]);
const paths = [];
for (const f of geo.features) {
  const id = want[f.properties.ADM0_A3];
  if (!id) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const d = polys.map((poly) => poly.map(ringPath).join('')).join('');
  if (d) paths.push({ id, d });
}
paths.sort((a, b) => (a.id === 'albania') - (b.id === 'albania')); // Albania painted last

const cities = Object.fromEntries(Object.entries(CITIES).map(([k, c]) => {
  const [x, y] = px([c.lon, c.lat]);
  return [k, { ...c, x, y, fx: +(x / W).toFixed(4), fy: +(y / H).toFixed(4) }];
}));

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<!-- Generated by scripts/build-map.mjs from Natural Earth (public domain). -->
${paths.map((p) => `<path id="${p.id}" class="land ${p.id === 'albania' ? 'home' : 'neighbour'}" d="${p.d}"/>`).join('\n')}
</svg>\n`;

const outDir = path.join(ROOT, 'assets/illustrations');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'albania-map.svg'), svg);
fs.writeFileSync(path.join(outDir, 'albania-map.json'), JSON.stringify({
  source: 'Natural Earth 1:10m admin-0 countries (public domain)', box: BOX, width: W, height: H,
  paths: Object.fromEntries(paths.map((p) => [p.id, p.d])), cities,
}, null, 1));
console.log(`albania-map: ${W}x${H}, ${paths.length} shapes, ${(svg.length / 1024).toFixed(0)} KB`);
